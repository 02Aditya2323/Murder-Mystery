/**
 * Beat 10 — The Accomplice. Builds the OSINT chain.
 *
 * Chain the players follow:
 *   club member's public bio  ->  base64 string
 *   base64 decodes to         ->  a URL on this event's own host
 *   that URL serves           ->  a QR image
 *   scanning the QR gives     ->  the flag (target) or a dead end (decoys)
 *
 * The QR images are served from apps/web/public/q/, so there is no external
 * hosting to arrange and nothing to break if a member's account is private.
 * Tokens are unguessable, so the set cannot be enumerated.
 *
 *   node scripts/gen-level10-osint.mjs            # uses http://localhost:3000
 *   node scripts/gen-level10-osint.mjs https://mystery.ecesa.in
 */
import QRCode from 'qrcode';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASE = (process.argv[2] || 'http://localhost:3000').replace(/\/+$/, '');
const OUT_DIR = path.join(ROOT, 'apps/web/public/q');
const DOC = path.join(ROOT, 'content/level10-osint.md');

const FLAG = 'FLAG{ROWAN_HALE}';

// One entry per club member whose profile will carry a string. Rename these to
// your actual volunteers before the event; exactly one must be the target.
const MEMBERS = [
  { handle: 'member-01', target: false },
  { handle: 'member-02', target: false },
  { handle: 'member-03', target: true },   // <- carries the flag
  { handle: 'member-04', target: false },
  { handle: 'member-05', target: false },
  { handle: 'member-06', target: false },
  { handle: 'member-07', target: false },
  { handle: 'member-08', target: false },
];

// What a decoy QR says. Deliberately in-world, so a team that scans one knows
// it is a dead end without feeling cheated.
const DEAD_ENDS = [
  'ARCHIVE REF 0001 - no liaison record held',
  'ARCHIVE REF 0002 - personnel file withheld',
  'ARCHIVE REF 0003 - no match for this badge',
  'ARCHIVE REF 0004 - request logged, no record',
  'ARCHIVE REF 0005 - duty roster only',
  'ARCHIVE REF 0006 - see Records, basement',
  'ARCHIVE REF 0007 - file closed 2023',
];

const token = () => crypto.randomBytes(9).toString('base64url');

fs.mkdirSync(OUT_DIR, { recursive: true });
for (const f of fs.readdirSync(OUT_DIR)) {
  if (f.endsWith('.png')) fs.unlinkSync(path.join(OUT_DIR, f));
}

let decoyIdx = 0;
const rows = [];

for (const m of MEMBERS) {
  const tok = token();
  const payload = m.target ? FLAG : DEAD_ENDS[decoyIdx++ % DEAD_ENDS.length];
  const url = `${BASE}/q/${tok}.png`;

  await QRCode.toFile(path.join(OUT_DIR, `${tok}.png`), payload, {
    width: 512,
    margin: 2,
    color: { dark: '#11161Cff', light: '#F2E9D4ff' }
  });

  rows.push({
    handle: m.handle,
    target: m.target,
    bio: Buffer.from(url, 'utf8').toString('base64'),
    url,
    payload
  });
}

const target = rows.find((r) => r.target);

const doc = `# Beat 10 — OSINT chain (ORGANISERS ONLY)

Generated by \`scripts/gen-level10-osint.mjs\` against \`${BASE}\`.
Re-run it if the event host changes; every token is regenerated and the old
images are deleted.

**The clue that points at the right profile is the number \`4417\`.** Put it in
the target member's bio alongside the base64 string, phrased in-world — for
example *"liaison 4417 · still owe the archive a coffee"*. Every other member
gets a string but no number.

## What to paste into each profile

| Member | Put this in the bio | Scanning their QR gives |
|---|---|---|
${rows.map((r) => `| \`${r.handle}\`${r.target ? ' **← TARGET, also add 4417**' : ''} | \`${r.bio}\` | ${r.target ? '**the flag**' : 'a dead end'} |`).join('\n')}

## The target's chain, end to end

1. Bio string: \`${target.bio}\`
2. Decodes to: ${target.url}
3. That page serves a QR image
4. Scanning it gives: \`${target.payload}\`
5. Which is what the team submits.

## Before the event

- [ ] Rename \`MEMBERS\` in the script to the real volunteers and re-run it.
- [ ] Get consent from every member whose profile is used.
- [ ] Decide whether the target is on LinkedIn or Instagram and keep it consistent.
- [ ] Instagram bios are about 150 characters; these strings are ${target.bio.length}, so they fit.
- [ ] **The account must be public.** A private profile breaks the level with no warning.
- [ ] Test the whole chain from a clean browser and from a phone camera.
- [ ] Keep a paper fallback at the desk in case a profile goes down mid-event.

## Files written

${rows.map((r) => `- \`apps/web/public/q/${r.url.split('/').pop()}\`${r.target ? '  ← the flag' : ''}`).join('\n')}
`;

fs.writeFileSync(DOC, doc, 'utf8');

console.log(`Wrote ${rows.length} QR images to apps/web/public/q/`);
console.log(`Target profile: ${target.handle}`);
console.log(`Target bio string: ${target.bio}`);
console.log(`  -> ${target.url}`);
console.log(`  -> ${target.payload}`);
console.log(`\nPaste-in instructions: content/level10-osint.md`);
